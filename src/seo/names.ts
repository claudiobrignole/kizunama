const bySlug = new Map(SEO_NAMES.map((entry) => [entry.slug, entry]));

export function getSeoName(slug: string): SeoName | undefined {
  return bySlug.get(slug);
}

export function findSeoNameByInput(input: string): SeoName | undefined {
  const key = input.normalize('NFKD').replace(/\p{M}/gu, '').toLowerCase().replace(/[^a-z]/g, '');
  return bySlug.get(key);
}

/** Katakana for the locale. Italian uses the override only when the sound differs. */
export function spellingFor(entry: SeoName, locale: 'en' | 'it'): string {
  if (locale === 'it' && entry.katakanaIt) return entry.katakanaIt;
  return entry.katakana;
}

export function noteFor(entry: SeoName, locale: 'en' | 'it'): string {
  return locale === 'it' ? entry.noteIt : entry.noteEn;
}

